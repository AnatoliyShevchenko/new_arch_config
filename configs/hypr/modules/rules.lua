-- Jellyfin Desktop всегда открывается на телевизоре.
-- Сам клиент уезжает на ARZOPA: она стоит в координатах (0,0), поэтому Qt
-- считает её primaryScreen, а на Wayland восстановить позицию окно не может.
hl.window_rule({
    name    = "jellyfin-on-tv",
    match   = { class = "org.jellyfin.JellyfinDesktop" },
    monitor = "HDMI-A-2",
})

-- Noctalia Settings
hl.window_rule({
    match = { class = "dev.noctalia.Noctalia" },
    float = true,
    size = { 1080, 920 },
})

local suppressMaximizeRule = hl.window_rule({
    -- Ignore maximize requests from all apps. You'll probably like this.
    name  = "suppress-maximize-events",
    match = { class = ".*" },

    suppress_event = "maximize",
})
-- suppressMaximizeRule:set_enabled(false)

hl.window_rule({
    -- Fix some dragging issues with XWayland
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },

    no_focus = true,
})

